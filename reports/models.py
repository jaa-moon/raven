"""
reports/models.py
-----------------
Pydantic data models for Raven autonomous pentesting agent.

Covers:
- ProjectProfile: Language, framework, routes, entry point, detected ports
- SandboxInfo: Container/process lifecycle status & URLs
- AgentFinding: Single confirmed or candidate vulnerability finding
- AttackChain: Multi-agent combined attack narrative
- FinalReport: Complete aggregated report output
- AttackMemory: RAG self-improving memory pattern
- RavenConfig: Config settings for scans and providers
"""

from __future__ import annotations

import uuid
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


def _short_id(prefix: str = "AGT") -> str:
    """Generates a short unique identifier for a finding."""
    return f"{prefix}-{uuid.uuid4().hex[:6].upper()}"


class ProjectProfile(BaseModel):
    """
    Structured profile of a target project generated by ProjectClassifier.

    Attributes:
        path: Absolute path string to target root.
        language: Detected primary language (Python, Node, Go, Java, etc.).
        framework: Detected web framework (Flask, Express, Spring Boot, etc.).
        entry_point: Main script or entry file to start the application.
        detected_port: Default or detected port the app runs on.
        dependencies: List of parsed dependency names and versions.
        detected_routes: List of pre-scan statically extracted endpoints.
        health_check_paths: Candidate HTTP paths for sandbox readiness checks.
        environment: Extra environment variables needed for runtime sandbox.
    """
    path: str
    language: str = "Unknown"
    framework: str = "Unknown"
    entry_point: str = ""
    detected_port: int = 5000
    dependencies: List[str] = Field(default_factory=list)
    detected_routes: List[str] = Field(default_factory=list)
    health_check_paths: List[str] = Field(default_factory=lambda: ["/health", "/api/health", "/healthz", "/", "/actuator/health"])
    environment: Dict[str, str] = Field(default_factory=dict)


class SandboxInfo(BaseModel):
    """
    Status and connection details for the running sandbox environment.

    Attributes:
        mode: Execution mode ('docker' or 'process').
        container_id: Docker container ID string if running in Docker.
        process_pid: Process ID integer if running as local fallback process.
        host: Target IP/hostname (usually 127.0.0.1 or localhost).
        port: Bound host port.
        base_url: Full base URL string (e.g., http://localhost:5000).
        started_at: ISO timestamp when sandbox was initialized.
        ready: Boolean flag indicating if target responded to health checks.
    """
    mode: Literal["docker", "process"]
    container_id: Optional[str] = None
    process_pid: Optional[int] = None
    host: str = "http://127.0.0.1"
    port: int = 5000
    base_url: str = "http://127.0.0.1:5000"
    started_at: str = Field(default_factory=lambda: datetime.now().isoformat())
    ready: bool = False


class AgentFinding(BaseModel):
    """
    A single vulnerability finding discovered by Agent 1 or Agent 2.

    Attributes:
        finding_id: Unique identifier (e.g. AGT1-A8F2C9).
        agent: Originating agent ('web_api' or 'auth_infra').
        vulnerability_type: Category (SQLi, XSS, JWTBypass, HardcodedSecret, etc.).
        severity: Impact rating (Critical, High, Medium, Low, Info).
        target_url: Endpoint where vulnerability was triggered.
        method: HTTP method used (GET, POST, etc.).
        parameter: Parameter or field targeted.
        payload_sent: Specific payload string tested.
        evidence: Response snippet confirming vulnerability.
        confirmed: True if AI analysis confirmed exploitability.
        ai_analysis: Detailed explanation of vulnerability mechanism.
        curl_poc: Executable curl command to reproduce probe.
        remediation: Actionable guidance to fix the issue.
        chain_opportunity: Optional hint for sister agent to exploit further.
    """
    finding_id: str = Field(default_factory=lambda: _short_id("AGT"))
    agent: Literal["web_api", "auth_infra"]
    vulnerability_type: str
    severity: Literal["Critical", "High", "Medium", "Low", "Info"] = "Medium"
    target_url: str = ""
    method: str = "GET"
    parameter: str = ""
    payload_sent: str = ""
    evidence: str = ""
    confirmed: bool = True
    ai_analysis: str = ""
    curl_poc: str = ""
    remediation: str = ""
    chain_opportunity: Optional[str] = None


class AttackChain(BaseModel):
    """
    Synthesized multi-stage attack path combining findings from both agents.

    Attributes:
        chain_id: Identifier for the attack chain.
        chain_name: Descriptive title (e.g., SQLi -> Auth Bypass -> Secrets Exfiltration).
        severity: Overall chain impact (Critical or High).
        agent_1_finding_ids: Associated findings from Agent 1 (Web/API).
        agent_2_finding_ids: Associated findings from Agent 2 (Auth/Infra).
        combined_impact: Narrative explaining full exploit impact.
        steps: Sequential execution steps.
        time_to_exploit: Estimated time for a human attacker.
    """
    chain_id: str = Field(default_factory=lambda: _short_id("CHN"))
    chain_name: str
    severity: Literal["Critical", "High"] = "High"
    agent_1_finding_ids: List[str] = Field(default_factory=list)
    agent_2_finding_ids: List[str] = Field(default_factory=list)
    combined_impact: str = ""
    steps: List[str] = Field(default_factory=list)
    time_to_exploit: str = "1-2 hours"


class FinalReport(BaseModel):
    """
    Aggregated final output of an autonomous Raven scan.

    Attributes:
        scan_id: Unique ID for the scan session.
        target_path: Path to target project directory.
        project_profile: Target stack profile.
        sandbox_info: Sandbox runtime details.
        scan_start: ISO timestamp scan start time.
        scan_end: ISO timestamp scan completion time.
        duration_seconds: Total scan duration in seconds.
        agent_1_findings: Web/API findings.
        agent_2_findings: Auth/Infra findings.
        attack_chains: Synthesized multi-agent attack chains.
        risk_score: Calculated score from 0.0 to 10.0.
        risk_label: Qualitative severity label.
        executive_summary: LLM-generated summary.
        remediation_plan: Prioritized action list.
    """
    scan_id: str = Field(default_factory=lambda: _short_id("SCN"))
    target_path: str
    project_profile: ProjectProfile
    sandbox_info: SandboxInfo
    scan_start: str = Field(default_factory=lambda: datetime.now().isoformat())
    scan_end: str = ""
    duration_seconds: float = 0.0
    agent_1_findings: List[AgentFinding] = Field(default_factory=list)
    agent_2_findings: List[AgentFinding] = Field(default_factory=list)
    attack_chains: List[AttackChain] = Field(default_factory=list)
    risk_score: float = 0.0
    risk_label: Literal["Critical", "High", "Medium", "Low", "Clean"] = "Clean"
    executive_summary: str = ""
    remediation_plan: List[str] = Field(default_factory=list)


class AttackMemory(BaseModel):
    """
    Persisted attack technique intelligence entry for self-improving RAG.

    Attributes:
        stack_fingerprint: Normalized target stack identifier (e.g. python+flask+sqlalchemy).
        technique: Attack technique title.
        payload_template: Reusable payload template string.
        success_rate: Ratio of confirmed exploits to attempts.
        scan_count: Total times attempted.
        confirmed_count: Total times confirmed.
        last_seen: ISO timestamp of last observation.
    """
    stack_fingerprint: str
    technique: str
    payload_template: str
    success_rate: float = 1.0
    scan_count: int = 1
    confirmed_count: int = 1
    last_seen: str = Field(default_factory=lambda: datetime.now().isoformat())


class RavenConfig(BaseModel):
    """
    Configuration options for scan execution.

    Attributes:
        provider: Provider key (ollama, openai, anthropic, gemini, openrouter).
        model: Selected LLM model name.
        api_key: Optional API key.
        depth: Scan depth ('quick', 'standard', 'deep').
        no_docker: If True, skip Docker detection and force process fallback.
        agent_mode: Which agents to run ('both', 'web', 'auth').
    """
    provider: str = "ollama"
    model: str = "qwen2.5:7b"
    api_key: Optional[str] = None
    depth: Literal["quick", "standard", "deep"] = "standard"
    no_docker: bool = False
    agent_mode: Literal["both", "web", "auth"] = "both"
    use_mcp: bool = False
